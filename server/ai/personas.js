// Helper: get a random persona filtered by side
// side: "believer" | "atheist" | undefined (any)
// ─────────────────────────────────────────────
export function getRandomPersona(side) {
  const pool =
    side ? personas.filter((p) => p.side === side) : personas;
  if (pool.length === 0) return null;
  return pool[Math.floor(Math.random() * pool.length)];
}

